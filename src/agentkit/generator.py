def _generate(root: Path, plan: dict[str, str], *, force: bool, dry_run: bool) -> list[Path]:
    """Write a plan additively and record what this version wrote, or already finds in place."""
    generated: list[Path] = []
    recorded: dict[str, str | bytes] = {}
    for relative, body in plan.items():
        path = root / relative
        if _write_text(path, body, force=force, dry_run=dry_run):
            generated.append(path)
            recorded[relative] = body
        elif _same_content(path, body):
            recorded[relative] = body
    if not dry_run:
        record_generated(root, recorded)
    return generated


def shipped_profiles() -> list[str]:
    """The stack profiles this version carries, by the name a manifest uses for them."""
    return sorted(path.parent.name for path in (package_root() / "profiles").glob("*/profile.toml"))


def _profile_commands(profiles: Sequence[str]) -> dict[str, str]:
    """The commands the chosen profiles name; where two name the same one, the first listed wins."""
    commands: dict[str, str] = {}
    for profile in profiles:
        path = package_root() / "profiles" / profile / "profile.toml"
        # a manifest may also name an adapter or a capability, which has no commands to give
        if not path.is_file():
            continue
        declared = tomllib.loads(path.read_text(encoding="utf-8")).get("commands", {})
        for key, value in declared.items():
            if value and key not in commands:
                commands[key] = value
    return commands


def install_scaffold(
    destination: Path,
    *,
    name: str,
    profiles: Sequence[str] = ("generic",),
    dry_run: bool = False,
) -> list[Path]:
    source = package_root()
    copied: list[Path] = []
    for relative in ("core", "hooks", "profiles"):
        src = source / relative
        dst = destination / relative
        if not dst.exists():
            if not dry_run:
                # a checkout that has run its tests holds bytecode caches next to the guards
                shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
                if relative == "hooks":
                    record_generated(destination, plan_hooks())
            copied.append(dst)
    manifest = destination / ".agent" / "project.toml"
    if not manifest.exists():
        listed = ", ".join(f'"{_toml_escape(profile)}"' for profile in profiles)
        # a project starts with the commands of its stack and changes them where its own differ
        commands = "".join(
            f'{key} = "{_toml_escape(value)}"\n'
            for key, value in _profile_commands(profiles).items()
        )
        body = f'''version = 1
protected_areas = [
  "authentication",
  "authorization",
  "database-schema",
  "billing",
]

[project]
name = "{_toml_escape(name)}"
topology = "monorepo"

[[repositories]]
id = "root"
path = "."
profiles = [{listed}]

[workflow]
require_spec = true
require_plan = true
require_review = true
require_qa = true
'''
        if commands:
            body += f"\n[commands]\n{commands}"
        if not dry_run:
            manifest.parent.mkdir(parents=True, exist_ok=True)
            manifest.write_text(body, encoding="utf-8")
        copied.append(manifest)
    instructions = destination / "AGENTS.md"
    if not instructions.exists():
        if not dry_run:
            instructions.parent.mkdir(parents=True, exist_ok=True)
            instructions.write_text(AGENT_INSTRUCTIONS, encoding="utf-8", newline="\n")
        copied.append(instructions)
    return copied


def update_hooks(root: Path, *, dry_run: bool = False) -> dict[str, list[str]]:
    """Bring a project's `hooks/` up to the guards this version ships.

    `init` never overwrites an existing `hooks/`, so a project keeps the guards it was created
    with, and settings regenerated by a newer version can name a guard it does not have. Guards
    are replaced by name; files the package does not ship are left alone.
    """
    result: dict[str, list[str]] = {"added": [], "updated": [], "unchanged": []}
    planned = plan_hooks()
    for relative, content in planned.items():
        destination = root / relative
        name = destination.name
        if not destination.exists():
            result["added"].append(name)
        elif not _same_content(destination, content):
            result["updated"].append(name)
        else:
            result["unchanged"].append(name)
            continue
        if not dry_run:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    if not dry_run:
        record_generated(root, planned)
    return result


def content_digest(data: str | bytes) -> str:
    """The hash a generated file is recorded under; line endings do not count."""
    raw = data.encode("utf-8") if isinstance(data, str) else data
    return hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()


def load_record(root: Path) -> dict[str, dict[str, str]]:
    """What `agentkit` last wrote in a project: relative path -> sha256 and version."""
    path = root / GENERATED_RECORD
    if not path.is_file():
        return {}
    try:
        files = json.loads(path.read_text(encoding="utf-8")).get("files", {})
    except (ValueError, AttributeError) as exc:
        raise ValueError(f"Unreadable generation record {path}: {exc}") from exc
    if not isinstance(files, dict):
        raise ValueError(f"Unreadable generation record {path}: files must be a table")
    return {
        str(key): {str(k): str(v) for k, v in value.items()}
        for key, value in files.items()
        if isinstance(value, dict)
    }


def record_generated(root: Path, written: Mapping[str, str | bytes]) -> None:
    """Remember the hash of each file this version wrote, so a later edit can be told apart."""
    files = load_record(root)
    changed = False
    for relative, body in written.items():
        digest = content_digest(body)
        # an unchanged entry keeps the version that wrote it, so the record does not churn
        if files.get(relative, {}).get("sha256") != digest:
            files[relative] = {"sha256": digest, "agentkit": __version__}
            changed = True
    if not changed:
        return
    path = root / GENERATED_RECORD
    path.parent.mkdir(parents=True, exist_ok=True)
    document = {"version": 1, "files": dict(sorted(files.items()))}
    path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8", newline="\n")


def _same_content(path: Path, body: str | bytes) -> bool:
    return path.is_file() and content_digest(path.read_bytes()) == content_digest(body)


def _write_text(path: Path, body: str, *, force: bool, dry_run: bool) -> bool:
    if path.exists() and not force:
        return False
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8", newline="\n")
    return True


def _toml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
