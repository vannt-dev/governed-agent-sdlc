# Tool matcher -> guard script under hooks/. PowerShell is the shell tool on Windows; MultiEdit and
# Task are the names older Claude Code versions use for multi-part edits and subagent spawns.
CLAUDE_GUARDS = (
    ("Bash|PowerShell|Read|Glob|Grep", "guard_credentials.py"),
    ("Bash|PowerShell", "guard_git.py"),
    ("Write|Edit|MultiEdit", "guard_role_scope.py"),
    ("Agent|Task", "guard_role_gate.py"),
)

AGENT_INSTRUCTIONS = """# Agent Instructions

Read `agentkit.toml` or `.agent/project.toml` before acting. Treat `core/` as the canonical source
of workflow and security policy. Require human approval where the manifest or core policy requires
it; never self-approve, force-push, merge, release, retrieve credentials, or print secrets.

Keep governed artifacts under `docs/agent/` with TOML frontmatter. Preserve unrelated changes and
run `agentkit validate` plus the configured project checks before reporting completion.
"""


def package_root() -> Path:
    checkout_root = Path(__file__).resolve().parents[2]
    if (checkout_root / "core").is_dir():
        return checkout_root
    resources = Path(__file__).resolve().parent / "resources"
    if (resources / "core").is_dir():
        return resources
    raise FileNotFoundError("Governed Agent SDLC scaffold resources are missing")


def generate_claude(root: Path, *, force: bool = False, dry_run: bool = False) -> list[Path]:
    return _generate(root, plan_claude(), force=force, dry_run=dry_run)


def plan_claude() -> dict[str, str]:
    """The Claude Code files this version writes, by path relative to the project."""
    planned: dict[str, str] = {}
    for role, model in ROLE_MODELS.items():
        tools = "Read, Glob, Grep, Bash, Write, Edit"
        planned[f".claude/agents/{role}.md"] = f"""---
name: {role}
description: Governed {role} role generated by Governed Agent SDLC. Invoke explicitly.
model: {model}
tools: {tools}
---

Read `AGENTS.md`, then read whichever of `agentkit.toml` or `.agent/project.toml` exists, and read
`core/roles/{role}.toml` before acting.
Stay within the role's declared authority and produce the required artifact evidence.
"""

    settings = {
        "permissions": {"deny": ["Read(**/.env)", "Read(**/.env.*)", "Read(**/*credential*)"]},
        "hooks": {
            "PreToolUse": [
                {
                    "matcher": matcher,
                    "hooks": [
                        {
                            "type": "command",
                            "command": f"uv run --no-project python hooks/{script}",
                            "timeout": 10,
                        }
                    ],
                }
                for matcher, script in CLAUDE_GUARDS
            ]
        },
    }
    planned[".claude/settings.json"] = json.dumps(settings, indent=2) + "\n"
    return planned


def generate_codex(root: Path, *, force: bool = False, dry_run: bool = False) -> list[Path]:
    """Generate additive project-scoped Codex configuration.

    Codex discovers the repository's existing AGENTS.md natively. The generated config only
    declares role-specific instruction layers and additive guard hooks; it never edits user-level
    trust, authentication, provider, model, telemetry, approval, or sandbox configuration.
    """
    return _generate(root, plan_codex(), force=force, dry_run=dry_run)


def plan_codex() -> dict[str, str]:
    """The Codex files this version writes, by path relative to the project."""
    planned: dict[str, str] = {}
    role_blocks: list[str] = []
    read_only_roles = {"architect", "planner", "reviewer", "qa", "publisher"}
    for role, description in ROLE_DESCRIPTIONS.items():
        role_prefix = 'sandbox_mode = "read-only"\n\n' if role in read_only_roles else ""
        planned[f".codex/agents/{role}.toml"] = role_prefix + (
            'developer_instructions = """\n'
            "Read AGENTS.md, the active project manifest, and "
            f"core/roles/{role}.toml before acting.\n"
            f"Operate only as the governed {role} role. "
            "Never self-approve, retrieve credentials, bypass protected branches, merge, or "
            "release without the required human decision.\n"
            '"""\n'
        )
        role_blocks.extend(
            [
                "",
                f"[agents.{role}]",
                f'description = "{description}"',
                f'config_file = "agents/{role}.toml"',
            ]
        )

    planned[".codex/hooks/pre_tool_use.py"] = (
        Path(__file__).with_name("codex_hook.py").read_text(encoding="utf-8")
    )
    hook_command = (
        'uv run --no-project python "$(git rev-parse --show-toplevel)/.codex/hooks/pre_tool_use.py"'
    )
    hook_command_windows = hook_command
    hooks = {
        "description": "Governed Agent SDLC credential and git safety guardrails.",
        "hooks": {
            "PreToolUse": [
                {
                    "matcher": "*",
                    "hooks": [
                        {
                            "type": "command",
                            "command": hook_command,
                            "commandWindows": hook_command_windows,
                            "timeout": 10,
                            "statusMessage": "Checking governed safety policy",
                        }
                    ],
                }
            ]
        },
    }
    planned[".codex/hooks.json"] = json.dumps(hooks, indent=2) + "\n"
    planned[".codex/config.toml"] = "\n".join(
        [
            'project_root_markers = [".git", "agentkit.toml", ".agent"]',
            "",
            "[features]",
            "multi_agent = true",
            "hooks = true",
            *role_blocks,
            "",
        ]
    )
    return planned


def _role_instructions(role: str) -> str:
    """What every generated role is told, whatever the tool that runs it."""
    return (
        "Read `AGENTS.md`, then read whichever of `agentkit.toml` or `.agent/project.toml` exists, "
        f"and read\n`core/roles/{role}.toml` before acting.\n"
        f"Operate only as the governed {role} role. Stay within its declared authority and "
        "produce the required\nartifact evidence. Never self-approve, retrieve credentials, bypass "
        "protected branches, merge, or\nrelease without the required human decision.\n"
    )


def generate_opencode(root: Path, *, force: bool = False, dry_run: bool = False) -> list[Path]:
    """Generate additive project-scoped OpenCode configuration.

    OpenCode reads the repository's AGENTS.md by itself. The adapter adds one subagent per role
    under `.opencode/agents/` and a plugin that asks the project's guards before a command runs
    or a file is read. Only the developer role may edit; every role is asked about shell commands.
    """
    return _generate(root, plan_opencode(), force=force, dry_run=dry_run)


def plan_opencode() -> dict[str, str]:
    """The OpenCode files this version writes, by path relative to the project."""
    planned: dict[str, str] = {}
    for role, description in ROLE_DESCRIPTIONS.items():
        edit = "allow" if role == "developer" else "deny"
        planned[f".opencode/agents/{role}.md"] = (
            "---\n"
            f"description: Governed {role} role generated by Governed Agent SDLC. {description}\n"
            "mode: subagent\n"
            "permission:\n"
            f"  edit: {edit}\n"
            "  bash: ask\n"
            "---\n\n" + _role_instructions(role)
        )
    planned[".opencode/plugins/governed-guards.js"] = OPENCODE_PLUGIN_SOURCE
    return planned


# The tools of Antigravity that run a command or reach a file; the hook is asked before each.
ANTIGRAVITY_GUARDED_TOOLS = ("run_command", "view_file", "find_by_name", "grep_search")


def generate_antigravity(root: Path, *, force: bool = False, dry_run: bool = False) -> list[Path]:
    """Generate additive project-scoped Antigravity configuration.

    Antigravity reads the repository's AGENTS.md by itself. The adapter adds one agent per role
    under `.agents/agents/<role>/agent.md` and a PreToolUse hook that asks the project's guards
    before a command runs or a file is read. An agent file has no permission keys there, so a
    role's limits are its instructions; the guards hold for every role.
    """
    return _generate(root, plan_antigravity(), force=force, dry_run=dry_run)


def plan_antigravity() -> dict[str, str]:
    """The Antigravity files this version writes, by path relative to the project."""
    planned: dict[str, str] = {}
    for role, description in ROLE_DESCRIPTIONS.items():
        planned[f".agents/agents/{role}/agent.md"] = (
            "---\n"
            f"name: {role}\n"
            f"description: Governed {role} role generated by Governed Agent SDLC. {description}\n"
            "---\n\n" + _role_instructions(role)
        )
    planned[".agents/hooks/governed_guard.py"] = (
        Path(__file__).with_name("antigravity_hook.py").read_text(encoding="utf-8")
    )
    hooks = {
        "governed-agent-sdlc": {
            "PreToolUse": [
                {
                    "matcher": "|".join(ANTIGRAVITY_GUARDED_TOOLS),
                    "hooks": [
                        {
                            "type": "command",
                            # run from the folder of hooks.json, so relative to `.agents/`
                            "command": "uv run --no-project python hooks/governed_guard.py",
                            "timeout": 30,
                        }
                    ],
                }
            ]
        }
    }
    planned[".agents/hooks.json"] = json.dumps(hooks, indent=2) + "\n"
    return planned


def plan_hooks() -> dict[str, bytes]:
    """The guards this version ships for a project's `hooks/`, by path relative to the project."""
    return {
        f"hooks/{path.name}": path.read_bytes()
        for path in sorted((package_root() / "hooks").glob("*.py"))
    }


