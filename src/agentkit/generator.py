from __future__ import annotations

import json
import shutil
import tomllib
from collections.abc import Sequence
from pathlib import Path

from agentkit.opencode_plugin import PLUGIN_SOURCE as OPENCODE_PLUGIN_SOURCE

ROLE_MODELS = {
    "architect": "opus",
    "planner": "opus",
    "developer": "sonnet",
    "reviewer": "opus",
    "qa": "sonnet",
    "publisher": "haiku",
}

ROLE_DESCRIPTIONS = {
    "architect": "Define approved specifications and system boundaries.",
    "planner": "Turn approved specifications into scoped task graphs.",
    "developer": "Implement only approved task scope and verification.",
    "reviewer": "Independently review changes without repairing source.",
    "qa": "Verify acceptance criteria and record reproducible evidence.",
    "publisher": "Publish only after review, QA, and human approval.",
}

# Tool matcher -> guard script under hooks/. PowerShell is the shell tool on Windows; MultiEdit and
# Task are the names older Claude Code versions use for multi-part edits and subagent spawns.
CLAUDE_GUARDS = (
    ("Bash|PowerShell|Read|Glob|Grep", "guard_credentials.py"),
    ("Bash|PowerShell", "guard_git.py"),
    ("Write|Edit|MultiEdit", "guard_role_scope.py"),
    ("Agent|Task", "guard_role_gate.py"),
)

AGENT_INSTRUCTIONS = """# Agent Instructions

Read `agentkit.toml` or `.agent/project.toml` before acting. Treat `core/` as the canonical source
of workflow and security policy. Require human approval where the manifest or core policy requires
it; never self-approve, force-push, merge, release, retrieve credentials, or print secrets.

Keep governed artifacts under `docs/agent/` with TOML frontmatter. Preserve unrelated changes and
run `agentkit validate` plus the configured project checks before reporting completion.
"""


def package_root() -> Path:
    checkout_root = Path(__file__).resolve().parents[2]
    if (checkout_root / "core").is_dir():
        return checkout_root
    resources = Path(__file__).resolve().parent / "resources"
    if (resources / "core").is_dir():
        return resources
    raise FileNotFoundError("Governed Agent SDLC scaffold resources are missing")


def generate_claude(root: Path, *, force: bool = False, dry_run: bool = False) -> list[Path]:
    claude = root / ".claude"
    agents = claude / "agents"
    generated: list[Path] = []

    for role, model in ROLE_MODELS.items():
        path = agents / f"{role}.md"
        if path.exists() and not force:
            continue
        tools = "Read, Glob, Grep, Bash, Write, Edit"
        body = f"""---
name: {role}
description: Governed {role} role generated by Governed Agent SDLC. Invoke explicitly.
model: {model}
tools: {tools}
---

Read `AGENTS.md`, then read whichever of `agentkit.toml` or `.agent/project.toml` exists, and read
`core/roles/{role}.toml` before acting.
Stay within the role's declared authority and produce the required artifact evidence.
"""
        if _write_text(path, body, force=force, dry_run=dry_run):
            generated.append(path)

    settings_path = claude / "settings.json"
    if force or not settings_path.exists():
        settings = {
            "permissions": {"deny": ["Read(**/.env)", "Read(**/.env.*)", "Read(**/*credential*)"]},
            "hooks": {
                "PreToolUse": [
                    {
                        "matcher": matcher,
                        "hooks": [
                            {
                                "type": "command",
                                "command": f"uv run --no-project python hooks/{script}",
                                "timeout": 10,
                            }
                        ],
                    }
                    for matcher, script in CLAUDE_GUARDS
                ]
            },
        }
        if not dry_run:
            settings_path.parent.mkdir(parents=True, exist_ok=True)
            settings_path.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")
        generated.append(settings_path)
    return generated


def generate_codex(root: Path, *, force: bool = False, dry_run: bool = False) -> list[Path]:
    """Generate additive project-scoped Codex configuration.

    Codex discovers the repository's existing AGENTS.md natively. The generated config only
    declares role-specific instruction layers and additive guard hooks; it never edits user-level
    trust, authentication, provider, model, telemetry, approval, or sandbox configuration.
    """

    codex = root / ".codex"
    generated: list[Path] = []
    role_blocks: list[str] = []
    read_only_roles = {"architect", "planner", "reviewer", "qa", "publisher"}
    for role, description in ROLE_DESCRIPTIONS.items():
        role_path = codex / "agents" / f"{role}.toml"
        role_prefix = 'sandbox_mode = "read-only"\n\n' if role in read_only_roles else ""
        role_body = role_prefix + (
            'developer_instructions = """\n'
            "Read AGENTS.md, the active project manifest, and "
            f"core/roles/{role}.toml before acting.\n"
            f"Operate only as the governed {role} role. "
            "Never self-approve, retrieve credentials, bypass protected branches, merge, or "
            "release without the required human decision.\n"
            '"""\n'
        )
        if _write_text(role_path, role_body, force=force, dry_run=dry_run):
            generated.append(role_path)
        role_blocks.extend(
            [
                "",
                f"[agents.{role}]",
                f'description = "{description}"',
                f'config_file = "agents/{role}.toml"',
            ]
        )

    hook_path = codex / "hooks" / "pre_tool_use.py"
    hook_source = Path(__file__).with_name("codex_hook.py").read_text(encoding="utf-8")
    if _write_text(hook_path, hook_source, force=force, dry_run=dry_run):
        generated.append(hook_path)

    hooks_path = codex / "hooks.json"
    hook_command = (
        'uv run --no-project python "$(git rev-parse --show-toplevel)/.codex/hooks/pre_tool_use.py"'
    )
    hook_command_windows = hook_command
    hooks = {
        "description": "Governed Agent SDLC credential and git safety guardrails.",
        "hooks": {
            "PreToolUse": [
                {
                    "matcher": "*",
                    "hooks": [
                        {
                            "type": "command",
                            "command": hook_command,
                            "commandWindows": hook_command_windows,
                            "timeout": 10,
                            "statusMessage": "Checking governed safety policy",
                        }
                    ],
                }
            ]
        },
    }
    if _write_text(
        hooks_path,
        json.dumps(hooks, indent=2) + "\n",
        force=force,
        dry_run=dry_run,
    ):
        generated.append(hooks_path)

    config = "\n".join(
        [
            'project_root_markers = [".git", "agentkit.toml", ".agent"]',
            "",
            "[features]",
            "multi_agent = true",
            "hooks = true",
            *role_blocks,
            "",
        ]
    )
    config_path = codex / "config.toml"
    if _write_text(config_path, config, force=force, dry_run=dry_run):
        generated.append(config_path)
    return generated


def _role_instructions(role: str) -> str:
    """What every generated role is told, whatever the tool that runs it."""
    return (
        "Read `AGENTS.md`, then read whichever of `agentkit.toml` or `.agent/project.toml` exists, "
        f"and read\n`core/roles/{role}.toml` before acting.\n"
        f"Operate only as the governed {role} role. Stay within its declared authority and "
        "produce the required\nartifact evidence. Never self-approve, retrieve credentials, bypass "
        "protected branches, merge, or\nrelease without the required human decision.\n"
    )


def generate_opencode(root: Path, *, force: bool = False, dry_run: bool = False) -> list[Path]:
    """Generate additive project-scoped OpenCode configuration.

    OpenCode reads the repository's AGENTS.md by itself. The adapter adds one subagent per role
    under `.opencode/agents/` and a plugin that asks the project's guards before a command runs
    or a file is read. Only the developer role may edit; every role is asked about shell commands.
    """

    opencode = root / ".opencode"
    generated: list[Path] = []
    for role, description in ROLE_DESCRIPTIONS.items():
        edit = "allow" if role == "developer" else "deny"
        body = (
            "---\n"
            f"description: Governed {role} role generated by Governed Agent SDLC. {description}\n"
            "mode: subagent\n"
            "permission:\n"
            f"  edit: {edit}\n"
            "  bash: ask\n"
            "---\n\n" + _role_instructions(role)
        )
        path = opencode / "agents" / f"{role}.md"
        if _write_text(path, body, force=force, dry_run=dry_run):
            generated.append(path)
    plugin_path = opencode / "plugins" / "governed-guards.js"
    if _write_text(plugin_path, OPENCODE_PLUGIN_SOURCE, force=force, dry_run=dry_run):
        generated.append(plugin_path)
    return generated


# The tools of Antigravity that run a command or reach a file; the hook is asked before each.
ANTIGRAVITY_GUARDED_TOOLS = ("run_command", "view_file", "find_by_name", "grep_search")


def generate_antigravity(root: Path, *, force: bool = False, dry_run: bool = False) -> list[Path]:
    """Generate additive project-scoped Antigravity configuration.

    Antigravity reads the repository's AGENTS.md by itself. The adapter adds one agent per role
    under `.agents/agents/<role>/agent.md` and a PreToolUse hook that asks the project's guards
    before a command runs or a file is read. An agent file has no permission keys there, so a
    role's limits are its instructions; the guards hold for every role.
    """

    agents = root / ".agents"
    generated: list[Path] = []
    for role, description in ROLE_DESCRIPTIONS.items():
        body = (
            "---\n"
            f"name: {role}\n"
            f"description: Governed {role} role generated by Governed Agent SDLC. {description}\n"
            "---\n\n" + _role_instructions(role)
        )
        path = agents / "agents" / role / "agent.md"
        if _write_text(path, body, force=force, dry_run=dry_run):
            generated.append(path)

    hook_path = agents / "hooks" / "governed_guard.py"
    hook_source = Path(__file__).with_name("antigravity_hook.py").read_text(encoding="utf-8")
    if _write_text(hook_path, hook_source, force=force, dry_run=dry_run):
        generated.append(hook_path)

    hooks = {
        "governed-agent-sdlc": {
            "PreToolUse": [
                {
                    "matcher": "|".join(ANTIGRAVITY_GUARDED_TOOLS),
                    "hooks": [
                        {
                            "type": "command",
                            # run from the folder of hooks.json, so relative to `.agents/`
                            "command": "uv run --no-project python hooks/governed_guard.py",
                            "timeout": 30,
                        }
                    ],
                }
            ]
        }
    }
    hooks_path = agents / "hooks.json"
    if _write_text(hooks_path, json.dumps(hooks, indent=2) + "\n", force=force, dry_run=dry_run):
        generated.append(hooks_path)
    return generated


def shipped_profiles() -> list[str]:
    """The stack profiles this version carries, by the name a manifest uses for them."""
    return sorted(path.parent.name for path in (package_root() / "profiles").glob("*/profile.toml"))


def _profile_commands(profiles: Sequence[str]) -> dict[str, str]:
    """The commands the chosen profiles name; where two name the same one, the first listed wins."""
    commands: dict[str, str] = {}
    for profile in profiles:
        path = package_root() / "profiles" / profile / "profile.toml"
        # a manifest may also name an adapter or a capability, which has no commands to give
        if not path.is_file():
            continue
        declared = tomllib.loads(path.read_text(encoding="utf-8")).get("commands", {})
        for key, value in declared.items():
            if value and key not in commands:
                commands[key] = value
    return commands


def install_scaffold(
    destination: Path,
    *,
    name: str,
    profiles: Sequence[str] = ("generic",),
    dry_run: bool = False,
) -> list[Path]:
    source = package_root()
    copied: list[Path] = []
    for relative in ("core", "hooks", "profiles"):
        src = source / relative
        dst = destination / relative
        if not dst.exists():
            if not dry_run:
                # a checkout that has run its tests holds bytecode caches next to the guards
                shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
            copied.append(dst)
    manifest = destination / ".agent" / "project.toml"
    if not manifest.exists():
        listed = ", ".join(f'"{_toml_escape(profile)}"' for profile in profiles)
        # a project starts with the commands of its stack and changes them where its own differ
        commands = "".join(
            f'{key} = "{_toml_escape(value)}"\n'
            for key, value in _profile_commands(profiles).items()
        )
        body = f'''version = 1
protected_areas = [
  "authentication",
  "authorization",
  "database-schema",
  "billing",
]

[project]
name = "{_toml_escape(name)}"
topology = "monorepo"

[[repositories]]
id = "root"
path = "."
profiles = [{listed}]

[workflow]
require_spec = true
require_plan = true
require_review = true
require_qa = true
'''
        if commands:
            body += f"\n[commands]\n{commands}"
        if not dry_run:
            manifest.parent.mkdir(parents=True, exist_ok=True)
            manifest.write_text(body, encoding="utf-8")
        copied.append(manifest)
    instructions = destination / "AGENTS.md"
    if not instructions.exists():
        if not dry_run:
            instructions.parent.mkdir(parents=True, exist_ok=True)
            instructions.write_text(AGENT_INSTRUCTIONS, encoding="utf-8", newline="\n")
        copied.append(instructions)
    return copied


def update_hooks(root: Path, *, dry_run: bool = False) -> dict[str, list[str]]:
    """Bring a project's `hooks/` up to the guards this version ships.

    `init` never overwrites an existing `hooks/`, so a project keeps the guards it was created
    with, and settings regenerated by a newer version can name a guard it does not have. Guards
    are replaced by name; files the package does not ship are left alone.
    """
    source = package_root() / "hooks"
    target = root / "hooks"
    result: dict[str, list[str]] = {"added": [], "updated": [], "unchanged": []}
    for path in sorted(source.glob("*.py")):
        destination = target / path.name
        content = path.read_bytes()
        if not destination.exists():
            result["added"].append(path.name)
        elif destination.read_bytes().replace(b"\r\n", b"\n") != content.replace(b"\r\n", b"\n"):
            result["updated"].append(path.name)
        else:
            result["unchanged"].append(path.name)
            continue
        if not dry_run:
            target.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    return result


def _write_text(path: Path, body: str, *, force: bool, dry_run: bool) -> bool:
    if path.exists() and not force:
        return False
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8", newline="\n")
    return True


def _toml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
