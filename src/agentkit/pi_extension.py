"""The Pi extension the Pi adapter writes out as `.pi/extensions/governed-guards.js`.

Pi calls an extension's `tool_call` handler with the tool's name and its input before the tool
runs, and a call is refused by returning `{block: true, reason}`. The extension decides nothing
itself: it puts the call into the words the project's guards in `hooks/` read and asks them, so
the rules stay in one place for every tool.
"""

from __future__ import annotations

EXTENSION_SOURCE = r"""// Generated by Governed Agent SDLC (`agentkit generate pi`).
//
// Before a shell command runs or a file is read, listed or searched for, the project's own guards
// in hooks/ are asked. A guard that objects, is missing or fails refuses the call: nothing that
// should have been checked is waved through. Pi loads this file only once the project is trusted.
import { spawnSync } from "node:child_process";
import { existsSync, realpathSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// `.pi/extensions/` is two folders below the project root. The extension goes by its own place,
// so it works when Pi is started in a subfolder.
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

const COMMAND_GUARDS = ["guard_credentials.py", "guard_git.py"];
const PATH_GUARDS = ["guard_credentials.py"];

// The session's folder as the guards resolve their own place (`/var` is `/private/var` on macOS,
// a short `RUNNER~1` name is the long one on Windows), so a delete is judged inside the project.
function folder(cwd) {
  try {
    return realpathSync.native(cwd);
  } catch {
    return cwd;
  }
}

// Pi's tools take a path as written, a leading `@` dropped (`@.env` reads `.env`).
const where = (value) => (typeof value === "string" ? value.replace(/^@/, "") : value);

// Pi's tool, as the name and the arguments the guards read. The pattern grep searches for is
// text, not a path, so it is not passed on.
const request = (tool_name, tool_input, cwd) => ({ tool_name, tool_input, cwd });
const REQUESTS = {
  bash: (input, cwd) => [
    COMMAND_GUARDS,
    request("Bash", { command: String(input.command ?? "") }, cwd),
  ],
  powershell: (input, cwd) => [
    COMMAND_GUARDS,
    request("PowerShell", { command: String(input.command ?? "") }, cwd),
  ],
  read: (input, cwd) => [PATH_GUARDS, request("Read", { file_path: where(input.path) }, cwd)],
  ls: (input, cwd) => [PATH_GUARDS, request("Read", { path: where(input.path) }, cwd)],
  find: (input, cwd) => [
    PATH_GUARDS,
    request("Glob", { pattern: where(input.pattern), path: where(input.path) }, cwd),
  ],
  grep: (input, cwd) => [
    PATH_GUARDS,
    request("Grep", { path: where(input.path), glob: where(input.glob) }, cwd),
  ],
};

function ask(root, guard, request) {
  const script = join(root, "hooks", guard);
  if (!existsSync(script)) {
    return `the guard hooks/${guard} is missing; restore it with \`agentkit update-hooks\``;
  }
  const result = spawnSync("uv", ["run", "--no-project", "python", script], {
    cwd: root,
    input: JSON.stringify(request),
    encoding: "utf8",
    timeout: 10000,
    windowsHide: true,
  });
  if (result.error) return `the guard hooks/${guard} could not run: ${result.error.message}`;
  if (result.status === 0) return null;
  const reason = String(result.stderr ?? "").trim().replace(/^BLOCKED:\s*/, "");
  if (result.status === 2 && reason) return reason;
  return `the guard hooks/${guard} failed (exit ${result.status})`;
}

export default function (pi) {
  pi.on("tool_call", async (event, ctx) => {
    const translate = REQUESTS[event?.toolName];
    if (!translate) return;
    try {
      const [guards, request] = translate(event.input ?? {}, folder(ctx?.cwd ?? process.cwd()));
      for (const guard of guards) {
        const reason = ask(ROOT, guard, request);
        if (reason) return { block: true, reason: `Governed Agent SDLC: ${reason}` };
      }
    } catch (error) {
      const reason = `Governed Agent SDLC: the guards could not be asked (${error})`;
      return { block: true, reason };
    }
  });
}
"""
