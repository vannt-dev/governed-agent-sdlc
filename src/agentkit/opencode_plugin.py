"""The OpenCode plugin the OpenCode adapter writes out as `.opencode/plugins/governed-guards.js`.

OpenCode calls a plugin's `tool.execute.before` with the tool and its arguments, and a call is
refused by throwing. The plugin decides nothing itself: it puts the call into the words the
project's guards in `hooks/` read and asks them, so the rules stay in one place for every tool.
"""

from __future__ import annotations

PLUGIN_SOURCE = r"""// Generated by Governed Agent SDLC (`agentkit generate opencode`).
//
// Before a shell command runs or a file is read or searched for, the project's own guards in
// hooks/ are asked. A guard that objects, is missing or fails refuses the call: nothing that
// should have been checked is waved through. Writing files is left to each agent's own
// `permission`, which only the developer role has.
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// `.opencode/plugins/` is two folders below the project root. The plugin goes by its own place:
// OpenCode's `worktree` is `/` outside a git repository, and its `directory` may be a subfolder.
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

const COMMAND_GUARDS = ["guard_credentials.py", "guard_git.py"];
const PATH_GUARDS = ["guard_credentials.py"];

// OpenCode's tool, as the name and the arguments the guards read.
const request = (tool_name, tool_input) => ({ tool_name, tool_input });
const REQUESTS = {
  bash: (args) => [COMMAND_GUARDS, request("Bash", { command: String(args.command ?? "") })],
  read: (args) => [PATH_GUARDS, request("Read", { file_path: args.filePath ?? args.path })],
  list: (args) => [PATH_GUARDS, request("Read", { path: args.path })],
  glob: (args) => [PATH_GUARDS, request("Glob", { pattern: args.pattern, path: args.path })],
  grep: (args) => [PATH_GUARDS, request("Grep", { path: args.path, glob: args.include })],
};

function ask(root, guard, request) {
  const script = join(root, "hooks", guard);
  if (!existsSync(script)) {
    return `the guard hooks/${guard} is missing; restore it with \`agentkit update-hooks\``;
  }
  const result = spawnSync("uv", ["run", "--no-project", "python", script], {
    cwd: root,
    input: JSON.stringify(request),
    encoding: "utf8",
    timeout: 10000,
    windowsHide: true,
  });
  if (result.error) return `the guard hooks/${guard} could not run: ${result.error.message}`;
  if (result.status === 0) return null;
  const reason = String(result.stderr ?? "").trim().replace(/^BLOCKED:\s*/, "");
  if (result.status === 2 && reason) return reason;
  return `the guard hooks/${guard} failed (exit ${result.status})`;
}

export const GovernedGuards = async () => {
  return {
    "tool.execute.before": async (input, output) => {
      const translate = REQUESTS[input?.tool];
      if (!translate) return;
      const [guards, request] = translate(output?.args ?? {});
      for (const guard of guards) {
        const reason = ask(ROOT, guard, request);
        if (reason) throw new Error(`Governed Agent SDLC: ${reason}`);
      }
    },
  };
};
"""
